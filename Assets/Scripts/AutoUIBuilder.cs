    void Start()
    {
        generator = GetComponent<TextureGenerator>();
        EnsureUIManager();

        Texture2D tex = new Texture2D(2, 2);
        tex.SetPixels(new Color[] { Color.white, Color.white, Color.white, Color.white });
        tex.Apply();
        whiteSprite = Sprite.Create(tex, new Rect(0, 0, 2, 2), new Vector2(0.5f, 0.5f));

        defaultFont = Resources.GetBuiltinResource<Font>("LegacyRuntime.ttf");
        if (defaultFont == null) defaultFont = Font.CreateDynamicFontFromOSFont("Arial", 12);

        EnsureEventSystem();
        BuildUI();

        if (generator != null)
        {
            generator.GenerateAndApply();
            RefreshStopsList();
            RefreshPngLayersList();

            if (generator.colorStops != null && generator.colorStops.Count > 0)
                SelectStop(0);
        }
    }

    private UIManager EnsureUIManager()
    {
        if (uiManager == null)
        {
            uiManager = GetComponent<UIManager>();
            if (uiManager == null) uiManager = FindFirstObjectByType<UIManager>();

            if (uiManager == null)
            {
                Debug.LogError("[AutoUIBuilder] No se encontró ningún componente UIManager en la escena.");
            }
        }
        return uiManager;
    }

    void EnsureEventSystem()
    {
        if (FindFirstObjectByType<EventSystem>() == null)
        {
            GameObject es = new GameObject("EventSystem");
            es.AddComponent<EventSystem>();
            es.AddComponent<StandaloneInputModule>();
        }
    }

