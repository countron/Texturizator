    private void RecalculateLayout()
    {
        if (content == null) return;

        float stopsHeight = (stopsContainer != null) ? stopsContainer.sizeDelta.y : 0f;
        float pngHeight = (pngLayersContainer != null) ? pngLayersContainer.sizeDelta.y : 0f;

        if (stopsContainer != null)
        {
            stopsContainer.anchoredPosition = new Vector2(0, -topSectionHeight);
        }

        if (middleSection != null)
        {
            middleSection.anchoredPosition = new Vector2(0, -(topSectionHeight + stopsHeight));
        }

        if (pngLayersContainer != null)
        {
            pngLayersContainer.anchoredPosition = new Vector2(0, -(topSectionHeight + stopsHeight + middleSectionHeight));
        }

        if (bottomSection != null)
        {
            bottomSection.anchoredPosition = new Vector2(0, -(topSectionHeight + stopsHeight + middleSectionHeight + pngHeight));
        }

        float totalHeight = topSectionHeight + stopsHeight + middleSectionHeight + pngHeight + bottomSectionHeight + 20f;
        content.sizeDelta = new Vector2(280, totalHeight);
    }

    private void HandleSatValClick(PointerEventData eventData)
    {
        if (satValMap == null) return;
        RectTransform rectTransform = satValMap.rectTransform;
        if (RectTransformUtility.ScreenPointToLocalPointInRectangle(rectTransform, eventData.position, eventData.pressEventCamera, out Vector2 localPoint))
        {
            Rect rect = rectTransform.rect;
            currentSat = Mathf.Clamp01((localPoint.x - rect.x) / rect.width);
            currentVal = Mathf.Clamp01((localPoint.y - rect.y) / rect.height);
            UpdateColor();
        }
    }

    private void UpdateColor()
    {
        currentColor = Color.HSVToRGB(currentHue, currentSat, currentVal);
        if (colorPreview != null) colorPreview.color = currentColor;

        if (generator != null && selectedStopIndex >= 0 && selectedStopIndex < generator.colorStops.Count)
        {
            generator.UpdateColorStopColor(selectedStopIndex, currentColor);
            if (selectedStopIndex < activeStopItems.Count && activeStopItems[selectedStopIndex] != null)
            {
                Transform prev = activeStopItems[selectedStopIndex].transform.Find("Preview");
                if (prev != null) prev.GetComponent<Image>().color = currentColor;
            }
        }
    }

    private void SelectStop(int index)
    {
        if (generator == null || index < 0 || index >= generator.colorStops.Count) return;
        selectedStopIndex = index;
        Color stopColor = generator.colorStops[index].color;

        Color.RGBToHSV(stopColor, out currentHue, out currentSat, out currentVal);
        currentColor = stopColor;
        if (colorPreview != null) colorPreview.color = currentColor;

        UpdateSatValTexture();
        RefreshStopsList();
    }

    void MoveStop(int index, int direction)
    {
        if (generator == null) return;
        int targetIndex = index + direction;
        if (targetIndex < 0 || targetIndex >= generator.colorStops.Count) return;

        TextureGenerator.ColorStop stopA = generator.colorStops[index];
        TextureGenerator.ColorStop stopB = generator.colorStops[targetIndex];

        float tempPos = stopA.position;
        stopA.position = stopB.position;
        stopB.position = tempPos;

        if (Mathf.Approximately(stopA.position, stopB.position))
        {
            stopA.position = Mathf.Clamp01(stopA.position - 0.05f);
            stopB.position = Mathf.Clamp01(stopB.position + 0.05f);
        }

        generator.colorStops[index] = stopB;
        generator.colorStops[targetIndex] = stopA;

        if (selectedStopIndex == index) selectedStopIndex = targetIndex;
        else if (selectedStopIndex == targetIndex) selectedStopIndex = index;

        generator.colorStops.Sort((a, b) => a.position.CompareTo(b.position));
        generator.GenerateAndApply();
        RefreshStopsList();
    }

    void RefreshStopsList()
    {
        float savedScrollPos = scrollRect != null ? scrollRect.verticalNormalizedPosition : 1f;

        for (int i = activeStopItems.Count - 1; i >= 0; i--)
        {
            if (activeStopItems[i] != null) Destroy(activeStopItems[i]);
        }
        activeStopItems.Clear();

        if (generator == null || generator.colorStops == null || stopsContainer == null) return;

        float yOffsetStops = 0;

        for (int i = 0; i < generator.colorStops.Count; i++)
        {
            int index = i;
            TextureGenerator.ColorStop stop = generator.colorStops[i];

            GameObject row = new GameObject("Stop_Row_" + i);
            row.transform.SetParent(stopsContainer, false);
            SetElementBounds(row, 12, yOffsetStops, 280, 22);

            GameObject imgObj = new GameObject("Preview");
            imgObj.transform.SetParent(row.transform, false);
            Image img = imgObj.AddComponent<Image>();
            img.sprite = whiteSprite;
            img.color = stop.color;
            img.raycastTarget = false;
            SetElementBounds(imgObj, 0, 0, 20, 22);

            GameObject sliderObj = CreateRawSlider(row.transform, stop.position, (val) => generator.UpdateColorStopPosition(index, val));
            SetElementBounds(sliderObj, 24, 2, 126, 18);

            GameObject btnUp = CreateRawButton(row.transform, "▲", new Color(0.25f, 0.4f, 0.5f), () => MoveStop(index, -1));
            SetElementBounds(btnUp, 154, 0, 24, 22);

            GameObject btnDown = CreateRawButton(row.transform, "▼", new Color(0.25f, 0.4f, 0.5f), () => MoveStop(index, 1));
            SetElementBounds(btnDown, 182, 0, 24, 22);

            Color btnColor = (index == selectedStopIndex) ? new Color(0.2f, 0.6f, 0.3f) : new Color(0.25f, 0.35f, 0.5f);
            GameObject btnSel = CreateRawButton(row.transform, "S", btnColor, () => SelectStop(index));
            SetElementBounds(btnSel, 210, 0, 26, 22);

            GameObject btnDel = CreateRawButton(row.transform, "X", new Color(0.6f, 0.2f, 0.2f), () => {
                generator.RemoveColorStop(index);
                if (selectedStopIndex >= generator.colorStops.Count) selectedStopIndex = Mathf.Max(0, generator.colorStops.Count - 1);
                RefreshStopsList();
            });
            SetElementBounds(btnDel, 240, 0, 26, 22);

            activeStopItems.Add(row);
            yOffsetStops -= 26f;
        }

        float dynamicStopsHeight = Mathf.Abs(yOffsetStops);
        stopsContainer.sizeDelta = new Vector2(280, dynamicStopsHeight);

        RecalculateLayout();

        if (scrollRect != null)
        {
            Canvas.ForceUpdateCanvases();
            scrollRect.verticalNormalizedPosition = Mathf.Clamp01(savedScrollPos);
        }
    }

    void GenerateSatValTexture()
    {
        satValTexture = new Texture2D(64, 64, TextureFormat.RGB24, false);
        satValTexture.wrapMode = TextureWrapMode.Clamp;
        UpdateSatValTexture();
        satValMap.texture = satValTexture;
    }

    void UpdateSatValTexture()
    {
        if (satValTexture == null) return;
        int size = satValTexture.width;
        for (int y = 0; y < size; y++)
        {
            float v = (float)y / (size - 1);
            for (int x = 0; x < size; x++)
            {
                float s = (float)x / (size - 1);
                satValTexture.SetPixel(x, y, Color.HSVToRGB(currentHue, s, v));
            }
        }
        satValTexture.Apply();
    }

    void SetAnchorTopLeft(RectTransform rect, float x, float y, float width, float height)
    {
        rect.anchorMin = new Vector2(0, 1);
        rect.anchorMax = new Vector2(0, 1);
        rect.pivot = new Vector2(0, 1);
        rect.anchoredPosition = new Vector2(x, y);
        rect.sizeDelta = new Vector2(width, height);
    }

    void SetElementBounds(GameObject go, float x, float y, float width, float height)
    {
        RectTransform rect = go.GetComponent<RectTransform>();
        if (rect == null) rect = go.AddComponent<RectTransform>();
        SetAnchorTopLeft(rect, x, y, width, height);
    }

