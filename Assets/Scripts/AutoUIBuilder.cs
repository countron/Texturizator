    private void MovePngLayer(int index, int direction)
    {
        int targetIndex = index + direction;
        if (generator == null || generator.stampLayers == null) return;
        if (targetIndex < 0 || targetIndex >= generator.stampLayers.Count) return;

        var temp = generator.stampLayers[index];
        generator.stampLayers[index] = generator.stampLayers[targetIndex];
        generator.stampLayers[targetIndex] = temp;

        if (selectedPngLayerIndex == index) selectedPngLayerIndex = targetIndex;
        else if (selectedPngLayerIndex == targetIndex) selectedPngLayerIndex = index;

        generator.GenerateAndApply();
        RefreshPngLayersList();
    }

    public void RefreshPngLayersList()
    {
        for (int i = activePngItems.Count - 1; i >= 0; i--)
        {
            if (activePngItems[i] != null) Destroy(activePngItems[i]);
        }
        activePngItems.Clear();

        if (generator == null || generator.stampLayers == null || pngLayersContainer == null) return;

        float yOffset = 0f;

        for (int i = 0; i < generator.stampLayers.Count; i++)
        {
            int index = i;
            var layer = generator.stampLayers[i];
            string layerName = (layer != null && !string.IsNullOrEmpty(layer.layerName)) ? layer.layerName : "Capa " + (i + 1);

            GameObject row = new GameObject("PNG_Row_" + i);
            row.transform.SetParent(pngLayersContainer, false);
            SetElementBounds(row, 12, yOffset, 280, 24);

            GameObject btnUp = CreateRawButton(row.transform, "▲", new Color(0.25f, 0.4f, 0.5f), () => MovePngLayer(index, -1));
            SetElementBounds(btnUp, 0, 0, 20, 24);

            GameObject btnDown = CreateRawButton(row.transform, "▼", new Color(0.25f, 0.4f, 0.5f), () => MovePngLayer(index, 1));
            SetElementBounds(btnDown, 22, 0, 20, 24);

            Color selColor = (index == selectedPngLayerIndex) ? new Color(0.2f, 0.55f, 0.35f) : new Color(0.22f, 0.3f, 0.4f);
            GameObject btnSel = CreateRawButton(row.transform, layerName, selColor, () => {
                selectedPngLayerIndex = index;
                RefreshPngLayersList();
                RefreshRightInspector();
            });
            SetElementBounds(btnSel, 44, 0, 180, 24);

            GameObject btnDel = CreateRawButton(row.transform, "X", new Color(0.6f, 0.2f, 0.2f), () => {
                generator.stampLayers.RemoveAt(index);
                if (selectedPngLayerIndex >= generator.stampLayers.Count) selectedPngLayerIndex = generator.stampLayers.Count - 1;
                generator.GenerateAndApply();
                RefreshPngLayersList();
                RefreshRightInspector();
            });
            SetElementBounds(btnDel, 226, 0, 30, 24);

            activePngItems.Add(row);
            yOffset -= 28f;
        }

        float dynamicPngHeight = Mathf.Abs(yOffset);
        pngLayersContainer.sizeDelta = new Vector2(280, dynamicPngHeight);

        RecalculateLayout();
    }

