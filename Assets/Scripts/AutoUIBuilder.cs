    void AddButtonGroup(Transform parent, string[] labels, Action<int> onClick, ref float yCursor)
    {
        float gap = 4f;
        float totalWidth = 240f;
        float buttonWidth = (totalWidth - ((labels.Length - 1) * gap)) / labels.Length;

        for (int i = 0; i < labels.Length; i++)
        {
            int index = i;
            GameObject btnObj = CreateRawButton(parent, labels[i], new Color(0.22f, 0.26f, 0.35f), () => onClick(index));
            SetElementBounds(btnObj, 12 + (i * (buttonWidth + gap)), yCursor, buttonWidth, 22);
        }

        yCursor -= 26f;
    }

